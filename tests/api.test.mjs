import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import http from 'node:http';

test('local API persists profile, notes, manual jobs, source controls and protects private routes', async () => {
  const port=32000+Math.floor(Math.random()*10000);
  const child=spawn(process.execPath,['src/server.mjs'],{cwd:new URL('..',import.meta.url),env:{...process.env,PORT:String(port),FIELDWORK_DB:':memory:'},stdio:['ignore','pipe','pipe']});
  const timeout=setTimeout(()=>child.kill(),20000);timeout.unref();
  try {
    await new Promise((resolve,reject)=>{child.stdout.on('data',b=>{if(b.toString().includes('ready'))resolve();});child.once('error',reject);child.once('exit',code=>reject(new Error(`Server exited: ${code}`)));});
    const origin=`http://127.0.0.1:${port}`;
    let cookie;
    const request=async(path,method='GET',data,headers={})=>{
      const res=await fetch(origin+path,{method,headers:{'Content-Type':'application/json',...(cookie?{Cookie:cookie}:{}),...headers},...(data===undefined?{}:{body:typeof data==='string'?data:JSON.stringify(data)})});
      const setCookie=res.headers.get('set-cookie');
      if(setCookie)cookie=setCookie.split(';')[0];
      return {status:res.status,data:await res.json()};
    };
    assert.equal((await request('/api/state')).status,401);
    const first={email:'first@example.com',password:'First-Password-123'};
    assert.equal((await request('/api/register','POST',first)).status,200);
    let result=await request('/api/state?mode=demo');assert.equal(result.data.jobs.length,12);
    const p={...result.data.profile,name:'Test Researcher',visa:'F-1',skills:['Python','PIV'],projects:'PIV research'};
    assert.equal((await request('/api/profile','PUT',p)).status,200);
    result=await request('/api/state');assert.equal(result.data.profile.name,'Test Researcher');assert.equal(result.data.jobs.length,0);
    assert.equal(result.data.sources.filter(source=>source.starter).length,5);
    const configured=await request('/api/discovery','PUT',{appId:'id-123',appKey:'test-secret'});
    assert.equal(configured.data.configured,true);
    assert.ok(!JSON.stringify((await request('/api/state')).data).includes('test-secret'));
    await request('/api/discovery','DELETE');
    for(const source of result.data.sources)await request(`/api/sources/${source.id}`,'PATCH',{enabled:false});
    await request('/api/activity/demo-1','PUT',{status:'applied',notes:'Contact mentor on Friday'});
    result=await request('/api/state?mode=demo');assert.equal(result.data.jobs[0].notes,'Contact mentor on Friday');
    const manual={title:'Summer PIV Intern',company:'Research Group',organization:'Academia',kind:'internship',url:'https://example.org/job',description:'PIV research. F-1 students with CPT are eligible.',year:2027,season:'Summer'};
    assert.equal((await request('/api/jobs','POST',manual)).status,201);
    result=await request('/api/state');assert.equal(result.data.jobs.length,1);assert.equal(result.data.jobs[0].eligibility.status,'explicit');
    const add=await request('/api/sources','POST',{provider:'greenhouse',company:'Test Company',organization:'Industry',slug:'test-company'});assert.equal(add.status,201);
    assert.equal((await request(`/api/sources/${add.data.id}`,'PATCH',{enabled:false})).data.enabled,false);
    assert.equal((await request(`/api/sources/${add.data.id}`,'DELETE')).status,200);
    assert.equal((await request('/api/refresh','POST',{})).status,400);
    assert.equal((await request('/api/schedule','PUT',{enabled:false,intervalHours:12})).status,200);
    assert.equal((await request('/api/schedule','PUT',{enabled:true,intervalHours:0})).status,400);
    const extracted=await request('/api/extract','POST','PIV experiments with MATLAB and Python',{'Content-Type':'application/octet-stream','x-filename':'resume.txt'});
    assert.ok(extracted.data.suggestions.skills.includes('MATLAB'));
    assert.equal((await request('/api/profile','PUT',p,{Origin:'https://untrusted.example'})).status,403);
    const hostStatus=await new Promise((resolve,reject)=>{const req=http.get(origin+'/api/state',{headers:{Host:'untrusted.example'}},res=>{res.resume();resolve(res.statusCode);});req.on('error',reject);});
    assert.equal(hostStatus,403);
    assert.equal((await fetch(origin+'/src/store.mjs')).status,404);
    assert.equal((await fetch(origin+'/data/fieldwork.sqlite')).status,404);
    const exported=await request('/api/export');assert.equal(exported.data.formatVersion,1);assert.equal(exported.data.profile.name,'Test Researcher');
    await request('/api/logout','POST');
    assert.equal((await request('/api/export')).status,401);
    assert.equal((await request('/api/login','POST',{...first,password:'Wrong-password-123'})).status,401);
    assert.equal((await request('/api/register','POST',{email:'second@example.com',password:'Second-Password-123'})).status,200);
    result=await request('/api/state');
    assert.equal(result.data.profile.name,'');
    assert.equal(result.data.jobs.length,0);
    const robotics=await request('/api/suggest','POST',{text:'ROS2 robotics and control systems'});
    assert.ok(robotics.data.areas.includes('Robotics & controls'));
    await request('/api/profile','PUT',{...result.data.profile,skills:robotics.data.skills,areas:robotics.data.areas,searchTerms:['robotics perception engineer']});
    result=await request('/api/state');
    assert.ok(result.data.discovery.terms.includes('robotics perception engineer'));
    assert.ok(!result.data.discovery.terms.some(term=>term.includes('particle image velocimetry')));
    assert.equal((await request('/api/state?mode=demo')).data.jobs[0].notes,'');
    assert.equal((await request('/api/login','POST',first)).status,200);
    assert.equal((await request('/api/state')).data.profile.name,'Test Researcher');
  } finally {clearTimeout(timeout);child.kill();await once(child,'exit');}
});
